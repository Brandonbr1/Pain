package jerios.painmod.utils;

public class BlockPos {

    public int x;
    public int y;
    public int z;


    public BlockPos(int x, int y, int z) {
        this.x = x;
        this.y = y;
        this.z = z;
    }

    public void set(int x, int y, int z)  {
        this.x = x;
        this.y = y;
        this.z = z;
    }




}
